		<div>
			<h2 class="text-2xl font-semibold tracking-tight">What molecular hydrogen is</h2>
			<p class="text-muted-foreground mt-3">
				Molecular hydrogen is the smallest, lightest molecule there is: two hydrogen atoms,
				electrically neutral, and mostly inert in the body. Its safety profile is one of the
				best-established things about it. Reviews of the clinical literature note a near absence of
				toxicity across every route it has been given, and deep-sea divers have breathed
				hydrogen-containing gas mixes for decades. The molecule inside your body is not the hazard;
				the flammable gas around the equipment is, which is why
				<a href="/safety" class="link">safety engineering</a> is a core part of everything we publish.
			</p>
		</div>

		<div>
			<h2 class="text-2xl font-semibold tracking-tight">The selective antioxidant</h2>
			<p class="text-muted-foreground mt-3">
				The landmark finding, published in <em>Nature Medicine</em> in 2007, is that hydrogen is a
				selective antioxidant. It reduces the hydroxyl radical, the most cytotoxic oxidant your
				cells produce, while ignoring the milder oxidants your body deliberately uses for signaling.
				Ordinary antioxidant supplements cannot make that distinction. And because hydrogen is so
				small, it goes where the damage happens: through cell membranes, across the blood-brain
				barrier, and into mitochondria themselves. The deeper mechanism is still debated in the
				literature, and we cover that honestly on the <a href="/research" class="link">Research</a>
				page.
			</p>
		</div>

		<div>
			<h2 class="text-2xl font-semibold tracking-tight">How people take it</h2>
			<ul class="text-muted-foreground mt-3 list-disc space-y-3 pl-6">
				<li>
					<span class="text-foreground font-medium">Hydrogen water.</span> Tablets that fizz into a glass,
					or generator machines and bottles. Simple and popular, but physics sets a hard ceiling: water
					saturates at about 1.6 ppm of hydrogen, and blood levels spike briefly and return to baseline
					within minutes. It is a small bolus, not a sustained dose.
				</li>
				<li>
					<span class="text-foreground font-medium">Inhalation.</span> Breathing dilute hydrogen gas from
					an electrolysis device. Supply is continuous, so blood and tissue levels rise and stay elevated
					for as long as you breathe it. Clinical studies typically use 1 to 4 percent inspired hydrogen.
				</li>
				<li>
					<span class="text-foreground font-medium">Topical and local.</span> Baths, wraps, and experimental
					applicators that deliver hydrogen directly to skin or eyes. An emerging area with interesting
					early data and large unknowns; we track it in the research notes.
				</li>
			</ul>
			<p class="text-muted-foreground mt-3">
				The honest comparison between water and inhalation is more interesting than the marketing
				version. A gulp of hydrogen water actually produces a far higher instantaneous concentration
				at the gut than low-dose inhalation produces in blood. Inhalation's advantage is time:
				continuous delivery for the whole session, with total delivered dose that scales with device
				output. Direct head-to-head human comparisons are still lacking, so anyone claiming
				certainty either way is ahead of the data.
			</p>
		</div>

		<div>
			<h2 class="text-2xl font-semibold tracking-tight">What the evidence supports</h2>
			<p class="text-muted-foreground mt-3">
				The strongest human data is in metabolic health (blood lipids and glucose, with multiple
				trials and a meta-analysis) and exercise recovery (lactate, fatigue, and repeated-sprint
				performance in athletes). There is an established supportive-care role alongside cancer
				treatment for reducing side effects, always under medical supervision. Neurological
				applications are mechanistically attractive but clinically unproven. And the lung-protection
				results that motivated this project, in smoke-exposure models, are animal studies:
				biological plausibility, not human proof. The graded breakdown with citations lives on the
				<a href="/research" class="link">Research</a>
				page.
			</p>
		</div>

		<div>
			<h2 class="text-2xl font-semibold tracking-tight">The hype problem</h2>
			<p class="text-muted-foreground mt-3">
				Hydrogen is marketed as a cure for nearly everything, usually by people selling a machine.
				That does real damage to a genuinely promising field. Our position: hydrogen has a
				remarkable safety profile, a real and unusual mechanism, encouraging human data in specific
